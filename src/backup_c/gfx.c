static void process_events(void) {
    if (!disp) return;
    XEvent e;
    ev_type = 0;
    while (XPending(disp) > 0) {
        XNextEvent(disp, &e);
        switch (e.type) {
        case Expose:
            break;
        case ButtonPress:
            ev_type = 1;
            ev_mouse_x = e.xbutton.x;
            ev_mouse_y = e.xbutton.y;
            ev_button = e.xbutton.button;
            break;
        case KeyPress:
            ev_type = 2;
            ev_key = XLookupKeysym(&e.xkey, 0);
            break;
        case ClientMessage:
            ev_type = 3; // close
            open = false;
            break;
        case MotionNotify:
            ev_mouse_x = e.xmotion.x;
            ev_mouse_y = e.xmotion.y;
            break;
        }
    }
}

static void put_pixel(int x, int y, unsigned long pixel) {
    XSetForeground(disp, gc, pixel);
    XDrawPoint(disp, win, gc, x, y);
}

void gfx_init(int w, int h, const char* title) {
    disp = XOpenDisplay(NULL);
    if (!disp) {
        fprintf(stderr, "[Magnetar] Cannot open X display\n");
        return;
    }
    screen = DefaultScreen(disp);
    win_w = w;
    win_h = h;

    win = XCreateSimpleWindow(disp, RootWindow(disp, screen),
                              100, 100, w, h, 1,
                              BlackPixel(disp, screen),
                              0x2d2d3f);

    XStoreName(disp, win, title);
    
    Atom wm_delete = XInternAtom(disp, "WM_DELETE_WINDOW", False);
    XSetWMProtocols(disp, win, &wm_delete, 1);
    
    XSelectInput(disp, win, ExposureMask | KeyPressMask | ButtonPressMask |
                           PointerMotionMask | StructureNotifyMask);
    
    gc = XCreateGC(disp, win, 0, NULL);
    cmap = DefaultColormap(disp, screen);
    cur_color.pixel = 0xffffff;
    XSetForeground(disp, gc, cur_color.pixel);
    
    XMapWindow(disp, win);
    XFlush(disp);
    open = true;
}

void gfx_close(void) {
    open = false;
}

bool gfx_is_open(void) {
    return open;
}

void gfx_clear(void) {
    if (!open || !disp) return;
    XClearWindow(disp, win);
}

void gfx_clear_color(int r, int g, int b) {
    if (!open || !disp) return;
    unsigned long pixel = (r << 16) | (g << 8) | b;
    XSetForeground(disp, gc, pixel);
    XFillRectangle(disp, win, gc, 0, 0, win_w, win_h);
}

void gfx_set_color(int r, int g, int b) {
    unsigned long pixel = (r << 16) | (g << 8) | b;
    cur_color.pixel = pixel;
    cur_color.red = r * 257;
    cur_color.green = g * 257;
    cur_color.blue = b * 257;
    cur_color.flags = DoRed | DoGreen | DoBlue;
    XAllocColor(disp, cmap, &cur_color);
    XSetForeground(disp, gc, cur_color.pixel);
}

void gfx_draw_line(int x1, int y1, int x2, int y2) {
    if (!open || !disp) return;
    XDrawLine(disp, win, gc, x1, y1, x2, y2);
}

void gfx_fill_rect(int x, int y, int w, int h) {
    if (!open || !disp) return;
    XFillRectangle(disp, win, gc, x, y, w, h);
}

void gfx_draw_rect(int x, int y, int w, int h) {
    if (!open || !disp) return;
    XDrawRectangle(disp, win, gc, x, y, w, h);
}

void gfx_draw_text(int x, int y, const char* text) {
    if (!open || !disp) return;
    size_t len = strlen(text);
    for (size_t i = 0; i < len; i++) {
        unsigned char c = (unsigned char)text[i];
        if (c < 32 || c > 126) { x += 8; continue; }
        int idx = c - 32;
        for (int row = 0; row < 8; row++) {
            unsigned char bits = font8x8[idx][row];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    XDrawPoint(disp, win, gc, x + col, y + row);
                }
            }
        }
        x += 7;
    }
}

void gfx_update(void) {
    if (!open || !disp) return;
    process_events();
    XFlush(disp);
}

